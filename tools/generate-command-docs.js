import {readFile,writeFile} from 'node:fs/promises';
import {commands} from '../dist/js/commands.js';

const target=new URL('../docs/commands.md',import.meta.url);
const cell=value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('|','\\|').replaceAll('`','&#96;').replace(/\r?\n/g,' ');
const rows=commands.map(command=>`| ${cell(command.name)} | ${cell(command.category)} | ${command.cmdlets.split(' · ').map(cmdlet=>`\`${cell(cmdlet)}\``).join(', ')} | ${cell(command.description)} |`);
const document=[
  '# Command catalog',
  '',
  '<!-- Generated by npm run docs:generate from dist/js/commands.js. Do not edit by hand. -->',
  '',
  `All ${commands.length} commands in catalog order. Names, categories, cmdlets, and descriptions come directly from the catalog.`,
  '',
  '| Action | Category | Main cmdlets | Purpose |',
  '| :--- | :--- | :--- | :--- |',
  ...rows,
  '',
  '[Documentation](README.md) · [Feature details](features.md)',
  ''
].join('\n');

if(process.argv.includes('--check')){
  let current;
  try{current=await readFile(target,'utf8');}catch(error){if(error.code!=='ENOENT')throw error;}
  if(current?.replaceAll('\r\n','\n')!==document){
    console.error('docs/commands.md is missing or out of date. Run npm run docs:generate and commit the result.');
    process.exitCode=1;
  }else console.log(`Command documentation is current (${commands.length} commands).`);
}else{
  await writeFile(target,document);
  console.log(`Generated docs/commands.md (${commands.length} commands).`);
}
